    # =====================================================
    # Layout abrufen
    # =====================================================

    @classmethod
    def get_text_layout(cls, shift=False):
        """
        Liefert das normale QWERTZ-Layout.

        shift=False:
            Kleinbuchstaben

        shift=True:
            Großbuchstaben
        """

        if shift:
            return cls.TEXT_UPPER

        return cls.TEXT_LOWER

    # =====================================================

    @classmethod
    def get_symbol_layout(cls):
        """
        Liefert das Sonderzeichenlayout.
        """

        return cls.SYMBOLS